"""
Scaffolder: Generates deployment-ready Solidity contracts and Hardhat scripts
from an AssetConfig.

What it generates:
1. A T-REX (ERC-3643) compliant token contract
2. An identity registry contract
3. A compliance contract with the rules from config
4. A Hardhat deployment script
5. A .env.example with all required environment variables

Why this matters:
Setting up ERC-3643 correctly takes weeks for teams unfamiliar with T-REX.
The Tokenization Factory from the ERC-3643 team is comprehensive but complex.
This scaffolder generates the minimum viable compliant deployment 
focused on the specific asset type.

Reference: https://github.com/TokenySolutions/T-REX
"""

